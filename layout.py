"""
layout.py

The on-disk shape of a generated dataset.

    <root>/
        manifest.json               every parameter the dataset was generated
                                    with, plus per-shard row counts
        graphs/
            shard_000/
                graphs.pt           {exp_id: [Data, ...]}, one Data per timestep
                labels.csv          one row per (experiment, timestep)
            shard_001/
                ...
        csv/
            shard_000/
                sensor_information.csv
                sensor_sectors.csv
                sensor_distances.csv
                sensor_detection_summary.csv
                phi_sector_scheme.csv
                drone_trajectories.csv
                drone_information.csv
                toa_measurements.csv
            shard_001/
                ...

WHY SHARDS
──────────
Each shard is simulated into its own SQLite database and exported
independently. A run of 200,000 experiments in one database is slow to write
and loses everything if it dies at 90%; the same run in 40 shards of 5,000 is
resumable, parallelizable across machines, and bounded in memory. Both outputs
of a shard come from that shard's single database, so the graph tensors and
the CSVs can never disagree about what was simulated.

EXPERIMENT IDS ARE PER-SHARD
────────────────────────────
Because each shard has its own database, `exp_id` restarts at 1 in every
shard. An experiment is identified by the pair (shard, exp_id), never by
`exp_id` alone.
"""

import json
import os

MANIFEST_FILENAME = "manifest.json"

GRAPHS_SUBDIR = "graphs"
CSV_SUBDIR = "csv"
REPORTS_SUBDIR = "reports"

GRAPH_SHARD_FILENAME = "graphs.pt"
LABELS_FILENAME = "labels.csv"

# Written by `csv_export`, in the order the generator produces them.
CSV_FILENAMES = [
    "sensor_information.csv",
    "sensor_sectors.csv",
    "sensor_distances.csv",
    "sensor_detection_summary.csv",
    "phi_sector_scheme.csv",
    "drone_trajectories.csv",
    "drone_information.csv",
    "toa_measurements.csv",
]


def shard_name(index):
    """`shard_000`, `shard_001`, ... — zero-padded so a plain sort is correct."""
    return f"shard_{index:03d}"


def graphs_root(root):
    return os.path.join(root, GRAPHS_SUBDIR)


def csv_root(root):
    return os.path.join(root, CSV_SUBDIR)


def reports_root(root):
    return os.path.join(root, REPORTS_SUBDIR)


def graph_dir(root, shard):
    return os.path.join(root, GRAPHS_SUBDIR, shard)


def csv_dir(root, shard):
    return os.path.join(root, CSV_SUBDIR, shard)


def graph_shard_path(root, shard):
    return os.path.join(graph_dir(root, shard), GRAPH_SHARD_FILENAME)


def labels_path(root, shard):
    return os.path.join(graph_dir(root, shard), LABELS_FILENAME)


def manifest_path(root):
    return os.path.join(root, MANIFEST_FILENAME)


def write_manifest(root, manifest):
    os.makedirs(root, exist_ok=True)
    with open(manifest_path(root), "w") as f:
        json.dump(manifest, f, indent=2, sort_keys=True)


def read_manifest(root):
    path = manifest_path(root)
    if not os.path.exists(path):
        raise FileNotFoundError(
            f"{path} not found — is {root!r} a dataset generated by `uav-sim generate`?")
    with open(path) as f:
        return json.load(f)


def list_shards(root):
    """
    Shard names present in both outputs of the dataset, sorted.
    """
    def present(base):
        if not os.path.isdir(base):
            return set()
        return {d for d in os.listdir(base) if os.path.isdir(os.path.join(base, d))}

    return sorted(present(graphs_root(root)) & present(csv_root(root)))
